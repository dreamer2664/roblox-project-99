local function addScript(parent, name, className, srcRel)
	-- fs.read with the "txt" format gives the raw script text (plain fs.read would
	-- hand back a Content object whose tostring is just the file stem)
	local source = fs.read(ROOT .. "/" .. srcRel, "txt")
	if type(source) ~= "string" then
		source = tostring(source)
	end
	local sc = Instance.new(className)
	sc.Name = name
	if #source == 0 then
		error("empty script " .. srcRel)
	end
	local ok, err = pcall(function()
		sc.Source = source
	end)
	if not ok then
		-- rbxmk cannot write Source; store it for the Rojo mirror instead
		print("NOTE: Source not writable in this environment (" .. tostring(err) .. ")")
		kit.setAttr(sc, "SourceExpected", #source)
	else
		print(string.format("script %-16s %6d bytes", name, #source))
	end
	sc.Parent = parent
	return sc
end

