--------------------------------------------------------------------------- manifest for renders
do
	local function vec(v)
		if not v then
			return { 0, 0, 0 }
		end
		return { math.floor((v.X or 0) * 100) / 100, math.floor((v.Y or 0) * 100) / 100,
			math.floor((v.Z or 0) * 100) / 100 }
	end
	local function cfAt(s, y)
		local cf = track.cframe(baked, s, y or 0)
		local look, right = nil, nil
		local cl = track.cframe(baked, s, 0)
		pcall(function()
			look = cl.LookVector
			right = cl.RightVector
		end)
		local smp = track.sample(baked, s)
		if not look then
			look = { X = math.cos(smp.h), Y = 0, Z = math.sin(smp.h) }
			right = { X = -math.sin(smp.h), Y = 0, Z = math.cos(smp.h) }
		end
		return { pos = vec(cf.Position), look = vec(look), right = vec(right) }
	end
	local manifest = {
		trackLength = baked.length,
		marks = marks,
		terminus1 = cfAt(0, 0),
		terminus1Platform = cfAt(60, 1.2),
		viaductMid = cfAt((marks.approachStart + marks.viaductEnd) / 2, 0),
		tunnelPortal = cfAt(marks.tunnelStart, 0),
		tunnelMid = cfAt((marks.tunnelStart + marks.tunnelEnd) / 2, 0),
		terminus2 = cfAt(marks.term2, 0),
		trains = {
			{ name = trains[1].name, s = trains[1].s, at = cfAt(trains[1].s, 0) },
			{ name = trains[2].name, s = trains[2].s, at = cfAt(trains[2].s, 0) },
		},
		cityCentre = vec((cfAt(0).pos)),
		partCount = kit.stats.parts,
		models = {},
	}
	-- bounding boxes for camera framing
	local function bbox(model)
		local mn = Vector3.new(1e9, 1e9, 1e9)
		local mx = Vector3.new(-1e9, -1e9, -1e9)
		for _, d in ipairs(model:GetDescendants()) do
			if d.ClassName == "Part" or d.ClassName == "WedgePart" then
				local p = d.CFrame.Position
				mn = Vector3.new(math.min(mn.X, p.X), math.min(mn.Y, p.Y), math.min(mn.Z, p.Z))
				mx = Vector3.new(math.max(mx.X, p.X), math.max(mx.Y, p.Y), math.max(mx.Z, p.Z))
			end
		end
		return { min = vec(mn), max = vec(mx) }
	end
	local ws = ctx.services.workspace
	for _, group in ipairs(ws:GetChildren()) do
		for _, md in ipairs(group:GetChildren()) do
			if md.ClassName == "Model" or md.ClassName == "Folder" then
				local name = group.Name .. "/" .. md.Name
				manifest.models[name] = bbox(md)
			end
		end
	end
	fs.write(OUT .. "/manifest.json", manifest)
	print("manifest written")
end

