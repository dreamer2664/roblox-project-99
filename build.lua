--------------------------------------------------------------------------- TrackData module (runtime alignment)
-- Serialised in compressed flat form so the driving script follows the exact spline
-- the rails were built from.
do
	local pts = baked.points
	local stride = math.max(1, math.floor(#pts / 1400))
	local flat = {}
	local s = {}
	for i = 1, #pts, stride do
		local p = pts[i]
		table.insert(flat, string.format("%.2f,%.2f,%.2f,%.4f,%.5f",
			p.p.X, p.p.Y, p.p.Z, p.h, p.k))
		table.insert(s, string.format("%.1f", p.s))
	end
	local src = table.concat({
		"--!nocheck",
		"-- TrackData: generated by build.lua -- the exact alignment used to lay the rails.",
		"-- Each entry: {s, x, y, z, heading, curvature}",
		"local TrackData = {}",
		"TrackData.Stride = " .. stride,
		"TrackData.Length = " .. string.format("%.2f", baked.length),
		"TrackData.Points = {",
		"\t" .. table.concat(flat, ",\n\t"),
		"}",
		"TrackData.Stations = {",
		string.format('\t{ name = "Grand Central Terminus", s = %.1f, stopAt = %.1f, side = "left" },', 60, 40),
		string.format('\t{ name = "Glanne Viaduct Halt", s = %.1f, stopAt = %.1f, side = "right" },',
			(marks.approachStart + marks.viaductEnd) / 2, (marks.approachStart + marks.viaductEnd) / 2),
		string.format('\t{ name = "Harbour Terminus", s = %.1f, stopAt = %.1f, side = "left" },',
			marks.term2 - 90, marks.term2 - 120),
		"}",
		"return TrackData",
	}, "\n")
	local ms = Instance.new("ModuleScript")
	ms.Name = "TrackData"
	local okSrc = pcall(function()
		ms.Source = src
	end)
	if not okSrc then
		kit.setAttr(ms, "SourceExpected", #src)
	end
	ms.Parent = svc.replicated
end

