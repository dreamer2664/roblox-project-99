local function writeModel(path, model, format)
	local ok, res = pcall(function()
		-- fs.write encodes by extension (rbxl = binary, rbxlx = xml)
		fs.write(path, model)
		return true
	end)
	if ok then
		print(string.format("%s written: %d bytes", path, fs.stat(path).Size))
	else
		print("ENCODE FAILED " .. tostring(res))
	end
end
