-- Place every consist on the alignment; each vehicle is individually aligned.
local function placeConsist(entry)
	local offset = 0
	for i, veh in ipairs(entry.metas) do
		local L = veh.length
		local s = entry.s + offset + L / 2
		local cf = track.cframe(baked, s, 0)
		kit.pivotTo(veh.model, cf)
		offset = offset + L + 0.8
	end
	kit.setAttr(entry.model, "StartS", entry.s)
	entry.model.Name = entry.name
end
for _, entry in ipairs(trains) do
	placeConsist(entry)
end

