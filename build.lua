-- rbxmk runs Lua 5.3-ish without Roblox's Random: provide a deterministic RNG so the
-- generated place is byte-for-byte reproducible.
if not math.clamp then
	function math.clamp(x, lo, hi)
		if x < lo then return lo end
		if x > hi then return hi end
		return x
	end
end
if not Random then
	Random = {}
end
if not Random.new then
	function Random.new(seed)
		local state = (seed or 12345) % 2147483647
		if state <= 0 then state = state + 2147483646 end
		local rng = {}
		function rng:_next()
			state = (state * 16807) % 2147483647
			return state / 2147483647
		end
		function rng:NextNumber(a, b)
			a = a or 0
			b = b or 1
			return a + (b - a) * self:_next()
		end
		function rng:NextInteger(a, b)
			return math.floor(self:NextNumber(a, b + 1))
		end
		return rng
	end
end

